#!/usr/bin/env python3
"""
export_moves.py - write the gameplay tables of your own International Karate (C64)
into a C header for the Uzebox port.

Usage:
  python3 export_moves.py tr_363717b0.pkl  ik_moves.h    (any trace from trace_stages.py)
  python3 export_moves.py ram.bin          ik_moves.h    (or a raw 64 KB RAM dump)

Also writes ik_sfx.h next to the header: the game's six sampled sound effects
(4-bit samples at $BF00-$CFFF, two per byte) converted to 8-bit PCM for the
Uzebox PCM channel, and the tables that decide which animation frame plays which.

Only data is exported. The rules that use it are implemented separately in the port's C code.
"""
import sys, pickle

def load(path):
    if path.endswith('.pkl'):
        return pickle.load(open(path, 'rb'))['ram']
    data = open(path, 'rb').read()
    if len(data) != 65536: raise SystemExit('expected a 65536-byte RAM dump')
    return data

# name, C64 address, length, comment
TABLES = [
    ('mv_bound',     0x2036,  36, 'first step of move n; move n ends where move n+1 starts'),
    ('st_frame',     0x205A, 200, 'fighter frame per step (>= 0x36 means frame 0)'),
    ('st_dx',        0x2122, 200, 'x movement per step (fat pixels, sign by facing)'),
    ('st_flags',     0x21E9, 200, 'step flags: 01 front 02 turn 04 hold point 08 chain 10 interruptible 20 end-hold 40 strike'),
    ('fr_width',     0x1E30,  54, 'visible width of each frame (arena clamping)'),
    ('joy_map',      0x1D02, 128, '4 x 32: normal facing R, normal facing L, block facing R, block facing L'),
    ('block_ok',     0x1CFA,   8, 'block allowed, indexed by relative position code'),
    ('sk_frame',     0x2BD7,   9, 'frames that count as a strike'),
    ('sk_reach',     0x2BE0,   9, 'strike point offset from fighter x'),
    ('sk_height',    0x2BE8,   9, 'zones a strike can reach (bit mask)'),
    ('sk_outer',     0x2BF0,   9, 'outer window (half point)'),
    ('sk_inner',     0x2BF8,   9, 'inner window (full point)'),
    ('sk_score_full',0x2C00,   9, 'score for a full point (BCD, x100)'),
    ('sk_score_half',0x2C08,   9, 'score for a half point (BCD, x100)'),
    ('sk_call_full', 0x2C10,   9, 'referee call / sound id, full point'),
    ('sk_call_half', 0x2C18,   9, 'referee call / sound id, half point'),
    ('zone_bit',     0x2C28,   6, 'bit of each of the 6 target zones'),
    ('sk_react',     0x2C2E,  36, 'victim reaction move, [strike*4 + facing code]'),
    ('pose_class',   0x2C4E,  54, 'victim frame -> pose class (bit 7 = cannot be hit)'),
    ('zone_off',     0x2C87, 162, 'zone x offset, [class*6 + zone] (bit 7 = no such zone)'),
]

# ------------------------------------------------------------------ sampled sound effects
C64_RATE = 985248.0 / 243.0          # CIA timer latch $00F2 -> one sample per 243 cycles (PAL)
UZE_NOTE = 11                        # kernel steptable[11] = 64: one sample per 4 mixer ticks
UZE_RATE = 15734.0 * 64 / 256

# effect: (first page, end page, high nibble?)  - read from the tables at $0DC7/$0DCD/$0DD9
def sample_ranges(ram):
    out = []
    for e in range(6):
        start = ram[0x0DCD + 2 * e] | ram[0x0DCE + 2 * e] << 8
        end = ram[0x0DC7 + e] << 8
        high = bool(ram[0x0DD9 + e] & 0x80)
        out.append((start, end, high))
    return out

def export_sfx(ram, path):
    import os
    lines = ['/* generated by export_moves.py from your own International Karate RAM dump:',
             ' * the six sampled sound effects as 8-bit PCM, plus the trigger tables. */',
             '#pragma once', '#define SFX_PCM_NOTE %d' % UZE_NOTE, '#define SFX_PCM_COUNT 6']
    TAIL = 64
    attack_fx = set(v for v in ram[0x0D42:0x0D42 + 11] if v < 6)
    for e, (start, end, high) in enumerate(sample_ranges(ram)):
        nib = [((b >> 4) if high else (b & 15)) for b in ram[start:end]]
        mean = sum(nib) / len(nib)
        n_out = int(len(nib) * UZE_RATE / C64_RATE)
        pcm = []
        for i in range(n_out):
            p = i * C64_RATE / UZE_RATE
            k = int(p); f = p - k
            a = nib[k]; b = nib[min(k + 1, len(nib) - 1)]
            v = int(round(((a + (b - a) * f) - mean) * 16))
            pcm.append(max(-128, min(127, v)))
        # fade the last few samples so the loop into silence doesn't click
        for i in range(min(32, len(pcm))):
            pcm[-1 - i] = int(pcm[-1 - i] * i / 32)
        # normalise to full scale; the samples played on attack frames (the punches and
        # kicks) get extra gain with soft clipping so they hit harder
        import math
        peak = max(1, max(abs(v) for v in pcm))
        boost = 1.8 if e in attack_fx else 1.0
        g = 127.0 / peak * boost
        pcm = [int(round(127 * math.tanh(v * g / 127.0) / math.tanh(boost))) for v in pcm]
        data = pcm + [0] * TAIL
        lines.append('#define SFX_PCM_LEN_%d %d      /* samples before the silent tail */' % (e, len(pcm)))
        lines.append('#define SFX_PCM_TICKS_%d %d    /* length in 60 Hz frames */' % (e, int(len(pcm) * 60 / UZE_RATE) + 1))
        lines.append('static const char sfx_pcm_%d[%d] PROGMEM = {%s};' % (e, len(data), ','.join(str(v) for v in data)))
    for name, addr in (('snd_key', 0x0D36), ('snd_attack', 0x0D42), ('snd_point', 0x0D4D),
                       ('snd_delay', 0x0D58), ('snd_delayed', 0x0D63), ('snd_bonus', 0x0D6E)):
        lines.append('static const u8 %s[11] PROGMEM = {%s};' % (name, ','.join(str(v) for v in ram[addr:addr + 11])))
    lines.append('#define SND_ATTACK_FLAGS 0x4D    /* step flags that make an attack frame sound */')
    open(path, 'w').write('\n'.join(lines) + '\n')
    return [len(l) for l in lines]

def main():
    if len(sys.argv) != 3: raise SystemExit(__doc__)
    ram = load(sys.argv[1])
    # sanity checks so a wrong dump fails loudly
    b = list(ram[0x2036:0x2036 + 36])
    if any(b[i] > b[i + 1] for i in range(35)) or b[35] > 200:
        raise SystemExit('move table looks wrong - is this a dump of International Karate in play/demo?')
    with open(sys.argv[2], 'w') as f:
        f.write('/* generated by export_moves.py from your own International Karate RAM dump */\n#pragma once\n')
        f.write('#define MOVE_COUNT 35\n#define STEP_COUNT %d\n' % b[35])
        for name, addr, n, comment in TABLES:
            data = ram[addr:addr + n]
            f.write('/* %s ($%04X) */\nstatic const u8 %s[%d] PROGMEM = {' % (comment, addr, name, n))
            f.write(', '.join('0x%02X' % v for v in data) + '};\n')
    print('wrote %s: %d moves, %d steps, %d tables' % (sys.argv[2], 35, b[35], len(TABLES)))
    import os
    sfx_path = os.path.join(os.path.dirname(os.path.abspath(sys.argv[2])), 'ik_sfx.h')
    export_sfx(ram, sfx_path)
    print('wrote %s: 6 sampled effects' % sfx_path)

if __name__ == '__main__':
    main()
